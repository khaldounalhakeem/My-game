export function say(coach, key, vars = {}) {
  const arr = coach.voice[key] || [];
  if (!arr.length) return '';
  const t = arr[Math.floor(Math.random() * arr.length)];
  return t.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

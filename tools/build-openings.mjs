// Builds data/openings.js from the lichess chess-openings TSV files (CC0).
import { readFileSync, writeFileSync } from 'fs';
import { Chess } from '../vendor/chess.js';

const epd = fen => fen.split(' ').slice(0, 4).join(' ');
const out = {};
for (const f of 'abcde') {
  const lines = readFileSync(new URL(`./openings/open_${f}.tsv`, import.meta.url), 'utf8').trim().split('\n').slice(1);
  for (const line of lines) {
    const [eco, name, pgn] = line.split('\t');
    const c = new Chess();
    for (const tok of pgn.split(/\s+/)) if (!/^\d+\./.test(tok)) c.move(tok);
    const k = epd(c.fen());
    // Prefer the shortest (most general) line name if two transpose.
    if (!out[k] || out[k][2] > c.history().length) out[k] = [eco, name, c.history().length];
  }
}
const compact = {};
for (const k in out) compact[k] = [out[k][0], out[k][1]];
writeFileSync(new URL('../data/openings.js', import.meta.url),
  '// Generated by tools/build-openings.mjs from lichess-org/chess-openings (CC0).\nexport const OPENINGS = ' + JSON.stringify(compact) + ';\n');
console.log(Object.keys(compact).length, 'positions');

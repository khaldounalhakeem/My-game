// Merges generated puzzle .jsonl files into data/puzzles.js (dedup, validate, assign ids).
import { readFileSync, readdirSync, writeFileSync } from 'fs';
import { Chess } from '../vendor/chess.js';

const dir = new URL('./puzzles/', import.meta.url);
const seen = new Set();
const out = [];
for (const f of readdirSync(dir).filter(f => f.endsWith('.jsonl')).sort()) {
  for (const line of readFileSync(new URL(f, dir), 'utf8').split('\n')) {
    if (!line.trim()) continue;
    const p = JSON.parse(line);
    const key = p.fen.split(' ').slice(0, 4).join(' ');
    if (seen.has(key)) continue;
    // validate the whole line is legal
    const c = new Chess(p.fen);
    let ok = true;
    for (const u of p.moves) { try { c.move({ from: u.slice(0, 2), to: u.slice(2, 4), promotion: u[4] }); } catch { ok = false; break; } }
    if (!ok || p.moves.length < 2 || p.moves.length % 2 !== 0) continue;
    if (p.themes.includes('mate') && !c.isCheckmate()) p.themes = p.themes.filter(t => !t.startsWith('mate'));
    seen.add(key);
    out.push(p);
  }
}
out.sort((a, b) => a.rating - b.rating);
const rows = out.map((p, i) => [`p${i + 1}`, p.fen, p.moves.join(' '), p.rating, p.themes.join(' ')]);
writeFileSync(new URL('../data/puzzles.js', import.meta.url),
  '// Generated by tools/gen-puzzles.mjs + tools/build-puzzles.mjs (Stockfish-verified).\n// [id, fen, moves (first move is the opponent\'s), rating, themes]\nexport const PUZZLES = ' + JSON.stringify(rows).replace(/\],\[/g, '],\n[') + ';\n');
console.log(out.length, 'puzzles');
